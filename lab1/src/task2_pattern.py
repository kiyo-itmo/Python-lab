"""
Задание 2: Узор "d" (7 строк, ширина 16).

Структура узора:
    - строка 1: полностью чёрная
    - строка 2: один блок по центру
    - строка 3: один блок по центру (как строка 2)
    - строка 4: полностью чёрная
    - строка 5: два блока, разделённые пробелами
    - строка 6: как строка 5
    - строка 7: полностью чёрная
"""

BLOCK = "#"        # символ "чёрного" блока
WIDTH = 16         # ширина узора в символах


def draw_one_d():
    """Рисует один узор "d" (7 строк)."""

    # Строка 1: полностью чёрная
    print(BLOCK * WIDTH)

    # Строка 2: 7 пробелов + 1 блок + 8 пробелов = 16
    print(" " * 7 + BLOCK + " " * 8)

    # Строка 3: то же самое (как строка 2)
    print(" " * 7 + BLOCK + " " * 8)

    # Строка 4: полностью чёрная
    print(BLOCK * WIDTH)

    # Строка 5: 3 пробела + 1 блок + 6 пробелов + 1 блок + 5 пробелов = 16
    print(" " * 3 + BLOCK + " " * 6 + BLOCK + " " * 5)

    # Строка 6: то же самое (как строка 5)
    print(" " * 3 + BLOCK + " " * 6 + BLOCK + " " * 5)

    # Строка 7: полностью чёрная
    print(BLOCK * WIDTH)


def draw_pattern(repeat=2):
    """
    Рисует узор "d" repeat раз.

    Параметры:
        repeat — сколько раз повторить узор
    """
    for _ in range(repeat):
        draw_one_d()
        print()  # пустая строка между повторами


if __name__ == "__main__":
    draw_pattern(repeat=2)